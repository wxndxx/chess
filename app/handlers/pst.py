def mirror_row(square: Square) -> Square:
    return Square(file=square.file, row=7 - square.row)


def piece_square_value(piece) -> int:
    table = PST[piece.name]

    if piece.color == Color.BLACK:
        square = mirror_row(piece.position)
    else:
        square = piece.position
    return table[square.row][square.file]
